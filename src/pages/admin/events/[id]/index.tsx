import { SuccessAlert } from "@/components/Alerts";
import { deleteEventGoogleWorkspace, getEventById, syncEventGoogleWorkspace, updateEvent } from "@/lib/apis/payments/client";
import { Event, hasRole, Roles } from "@/lib/apis/payments/models";
import { useEffect, useState } from "react";
import { createPortal } from "react-dom";
import EventFields from "@/components/events/EventFields";
import { Container } from "@/components/layout/SideBar";
import Head from "next/head";
import Link from "next/link";
import { PageHeader, PageMain } from "@/components/layout/PageHeader";
import { useRouter } from "next/router";
import useUser from "@/lib/hooks/useUser";

const SyncEvent = ({ event }: { event: Event }) => {
    const [syncing, setSyncing] = useState(false)

    const onSync = async () => {
        setSyncing(true);
        // Save pending changes (e.g. description) so the calendar gets the current data
        // const saved = await updateEvent(event);
        // if (saved.errors) {
        //     setSyncing(false);
        //     return;
        // }
        const response = await syncEventGoogleWorkspace(event.id);
        if (response.data) {
            window.location.reload();
        }
        setSyncing(false);
    }

    return (
        <div>
            <button
                disabled={syncing}
                onClick={onSync}
                className="btn btn-secondary w-full"
                type="button">
                {syncing ? "Sincronitzant..." : "Sincronitzar amb Google Calendar"}
            </button>
        </div>
    )
}

const DeleteCalendarEvent = ({ eventId }: { eventId: number }) => {
    const [deleting, setDeleting] = useState(false)

    const onDelete = async () => {
        setDeleting(true);
        const response = await deleteEventGoogleWorkspace(eventId);
        if (!response.errors) {
            window.location.reload();
        }
        setDeleting(false);
    }

    return (
        <div className="mt-3">
            <button
                disabled={deleting}
                onClick={onDelete}
                className="btn btn-danger w-full"
                type="button">
                {deleting ? "Eliminant..." : "Eliminar de Google Calendar"}
            </button>
        </div>
    )
}

const GoogleCalendar = ({ event }: { event: Event }) => {
    const { user, loading } = useUser();


    if (loading || !hasRole(user?.role, Roles.AdvancedAdmin)) {
        return null;
    }

    return (
        <div className="card mt-6 p-6 sm:p-8">
            <h2 className="section-title">Google Calendar</h2>
            <p className="mb-5 mt-1 text-sm text-slate-500">
                {event.calendarEventId ? "Aquest esdeveniment està sincronitzat amb el calendari." : "Aquest esdeveniment encara no és al calendari."}
            </p>
            <SyncEvent event={event} />
            {event.calendarEventId ? <DeleteCalendarEvent eventId={event.id} /> : null}
        </div>
    )
}

const Update = () => {
    const router = useRouter()
    const { id } = router.query
    const [loading, setLoading] = useState(false)
    const [updated, setUpdated] = useState(false)
    const [mounted, setMounted] = useState(false)
    const [errors, setErrors] = useState<Map<string, string[]>>()
    const [event, setEvent] = useState<Event | undefined>(undefined)

    useEffect(() => setMounted(true), [])

    useEffect(() => {
        if (!id) return;
        getEventById(parseInt(id as string))
            .then(x => {
                if (!x.data) {
                    return;
                }
                setEvent(x.data)
            });
    }, [id])


    const onSubmit = async (e: Event) => {
        setLoading(true);
        setUpdated(false);

        const data = await updateEvent(e);
        if (data.errors) {
            setErrors(data.errors);
        }
        else {
            setUpdated(true);
            setTimeout(() => setUpdated(false), 1500);
        }
        setLoading(false);
    }

    const onFormSubmit = async (e: React.SyntheticEvent<HTMLFormElement>) => {
        e.preventDefault();
        setErrors(undefined);
        if (!event) return;

        await onSubmit(event);
    }

    const formDisabled = () => loading;
    if (!event) return null;

    return (
        <>
            <Head>
                <title>Editar esdeveniment - {process.env.SCHOOL_NAME}</title>
                <meta name="description" content="Generated by create next app" />
                <meta name="viewport" content="width=device-width, initial-scale=1" />
                <link rel="icon" href="/favicon.ico" />
            </Head>
            <PageMain narrow>
                <PageHeader
                    title="Editar esdeveniment"
                    subtitle={<span className="inline-flex items-center gap-2">{event.name} <span className="badge badge-gray font-mono">{event.code}</span></span>}
                    back={{ href: "/admin/events", text: "Esdeveniments" }}
                    actions={<>
                        <Link className="btn btn-secondary" href={`/admin/events/${event.code}/people`}>Persones</Link>
                        <Link className="btn btn-secondary" href={`/admin/events/${event.code}/payments`}>Pagaments</Link>
                    </>} />
                <div>
                    <div>
                        {updated && mounted ? createPortal(
                            <div className="fixed right-4 top-4 z-[100] w-full max-w-sm">
                                <SuccessAlert text="Event editat correctament." />
                            </div>,
                            document.body
                        ) : null}

                        <form className="card p-6 sm:p-8" action="#" method="post" onSubmit={onFormSubmit} autoComplete="off">
                            <EventFields
                                errors={errors}
                                event={event}
                                setEvent={setEvent} />
                            <div>
                                <input
                                    disabled={formDisabled()}
                                    className="btn btn-primary mt-8 w-full"
                                    value="Guardar Canvis"
                                    type="submit" />
                            </div>
                        </form>

                        <GoogleCalendar event={event} />

                    </div>
                </div>
            </PageMain>
        </>

    )
}

export default function UpdateEventPage() {
    return (
        <Container>
            <Update />
        </Container>
    )
};

